-- ==============================================================================
-- Personnel Certificate Management System - Complete Master Schema (v3)
-- Includes:
--   1. personnel (บุคลากร พร้อมช่องทางแจ้งเตือนส่วนตัว และเปิด/ปิดชื่อ)
--   2. certificates (ใบประกาศนียบัตร 1 คนมีได้หลายใบ)
--   3. user_profiles (การอนุมัติผู้ใช้ และ Role Admin/Staff)
--   4. master_positions (ตำแหน่งงาน จัดการได้)
--   5. master_cert_types (ประเภทใบประกาศ จัดการได้)
-- ==============================================================================

-- 1. Table: personnel
CREATE TABLE IF NOT EXISTS public.personnel (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    position TEXT,
    email TEXT,
    discord_webhook_url TEXT,
    enable_discord BOOLEAN DEFAULT TRUE NOT NULL,
    enable_email BOOLEAN DEFAULT TRUE NOT NULL,
    is_active BOOLEAN DEFAULT TRUE NOT NULL,
    note TEXT,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 2. Table: certificates
CREATE TABLE IF NOT EXISTS public.certificates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    personnel_id BIGINT REFERENCES public.personnel(id) ON DELETE CASCADE NOT NULL,
    cert_name TEXT NOT NULL,
    cert_no TEXT,
    expire_date DATE,
    status_note TEXT,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 3. Table: user_profiles (User Approval Workflow)
CREATE TABLE IF NOT EXISTS public.user_profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    email TEXT NOT NULL,
    full_name TEXT,
    role TEXT DEFAULT 'staff' NOT NULL, -- 'admin' | 'staff'
    status TEXT DEFAULT 'pending' NOT NULL, -- 'pending' | 'approved' | 'rejected'
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 4. Table: master_positions
CREATE TABLE IF NOT EXISTS public.master_positions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT UNIQUE NOT NULL,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 5. Table: master_cert_types
CREATE TABLE IF NOT EXISTS public.master_cert_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT UNIQUE NOT NULL,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- Indexes
CREATE INDEX IF NOT EXISTS idx_personnel_name ON public.personnel (name);
CREATE INDEX IF NOT EXISTS idx_personnel_is_active ON public.personnel (is_active);
CREATE INDEX IF NOT EXISTS idx_certificates_personnel_id ON public.certificates (personnel_id);
CREATE INDEX IF NOT EXISTS idx_certificates_expire_date ON public.certificates (expire_date);
CREATE INDEX IF NOT EXISTS idx_user_profiles_status ON public.user_profiles (status);

